_EVENTS_BY_CODE: dict[str, CatalogEvent] = {e.event_code: e for e in ALL_EVENTS}


def get_event(event_code: str) -> CatalogEvent | None:
    """Return a catalog event by code, or None."""
    return _EVENTS_BY_CODE.get(event_code)


def list_events_by_group(group_prefix: str) -> list[CatalogEvent]:
    """Return all events whose group prefix matches (e.g. ``auth``)."""
    prefix = group_prefix.rstrip('.')
    return [e for e in ALL_EVENTS if e.group == prefix]


def recipient_types_allowed(event_code: str) -> frozenset[str]:
    """Recipient types allowed for an event (always includes custom when in catalog)."""
    event = get_event(event_code)
    if event is None:
        return frozenset()
    return frozenset(event.recipient_types)

